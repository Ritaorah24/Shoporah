package com.rita.ecommerceplatform.model.entity

import java.math.BigDecimal
import java.time.LocalDateTime

/**
 * One row of public.ec_product, plus its category name joined from ec_category.
 * Brand, keywords and the rating/sold summary columns are not used yet (D1), so they are left out.
 */
data class Product(
    var productId: Long? = null,
    var productCategoryId: Int? = null,
    var categoryName: String? = null,
    var productName: String? = null,
    var productDescription: String? = null,
    var productSku: String? = null,
    var productPrice: BigDecimal? = null,
    var productDiscountPrice: BigDecimal? = null,
    // Generated by the database: productDiscountPrice when set, otherwise productPrice.
    var productSellingPrice: BigDecimal? = null,
    var productStockQuantity: Int? = null,
    var productLowStockThreshold: Int? = null,
    var productCreatedByAdminId: Int? = null,
    var productStatus: ProductStatus? = null,
    var productCreatedAt: LocalDateTime? = null,
    var productUpdatedAt: LocalDateTime? = null,
) {
    /**
     * What the public sees instead of the exact stock (D4). LOW_STOCK only applies when the
     * admin has set a threshold.
     */
    fun availability(): Availability = when {
        productStockQuantity!! <= 0 -> Availability.OUT_OF_STOCK
        productLowStockThreshold != null && productStockQuantity!! <= productLowStockThreshold!! -> Availability.LOW_STOCK
        else -> Availability.IN_STOCK
    }
}

/** Public stock indicator derived from the stock quantity; never stored. */
enum class Availability { IN_STOCK, LOW_STOCK, OUT_OF_STOCK }

/** Allowed values of ec_product.productstatus (ck__ec_product__status). DELETED is a soft delete. */
enum class ProductStatus { ACTIVE, INACTIVE, DELETED }
