-- =====================================================================
-- V2: System parameters (single settings row)
-- =====================================================================
-- Secrets (JWT, payment keys) are NOT stored here; they belong in
-- environment variables / secure configuration (PRD section 10).
-- Default values are placeholders pending confirmation (RC-1, RC-17, RC-23).
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.ec_sys_param (
    sysparamid                          INTEGER     NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    sysparamplatformname                CITEXT      NOT NULL DEFAULT 'E-Commerce Platform',
    sysparamsupportemail                CITEXT,
    sysparamsupportphone                CITEXT,
    sysparamcurrencycode                CITEXT      NOT NULL DEFAULT 'NGN',
    sysparammaxloginattempts            INTEGER     NOT NULL DEFAULT 5,
    sysparamlockoutdurationminutes      INTEGER     NOT NULL DEFAULT 15,
    sysparampasswordresetexpiryminutes  INTEGER     NOT NULL DEFAULT 30,
    sysparamdefaultlowstockthreshold    INTEGER     NOT NULL DEFAULT 5,
    sysparamstatus                      CITEXT      NOT NULL DEFAULT 'ACTIVE',
    sysparamcreatedat                   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    sysparamupdatedat                   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_sysparam__id PRIMARY KEY (sysparamid),
    CONSTRAINT ck__ec_sysparam__maxloginattempts            CHECK (sysparammaxloginattempts > 0),
    CONSTRAINT ck__ec_sysparam__lockoutdurationminutes      CHECK (sysparamlockoutdurationminutes > 0),
    CONSTRAINT ck__ec_sysparam__passwordresetexpiryminutes  CHECK (sysparampasswordresetexpiryminutes > 0),
    CONSTRAINT ck__ec_sysparam__defaultlowstockthreshold    CHECK (sysparamdefaultlowstockthreshold >= 0),
    CONSTRAINT ck__ec_sysparam__status                      CHECK (sysparamstatus IN ('ACTIVE', 'INACTIVE'))
);
