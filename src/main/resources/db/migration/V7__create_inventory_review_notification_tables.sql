-- ---------------------------------------------------------------------
-- ec_inventory_movement : append-only log of every stock change (RC-18)
--   ec_product.productstockquantity remains the source of truth;
--   quantitychange is signed (+ restock/return, - sale/adjustment).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_inventory_movement (
    inventorymovementid             BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    inventorymovementproductid      BIGINT      NOT NULL,
    inventorymovementtype           CITEXT      NOT NULL,
    inventorymovementquantitychange INTEGER     NOT NULL,
    inventorymovementstockafter     INTEGER     NOT NULL,
    inventorymovementorderid        BIGINT,
    inventorymovementadminid        INTEGER,
    inventorymovementnote           TEXT,
    inventorymovementcreatedat      TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_inventorymovement__id             PRIMARY KEY (inventorymovementid),
    CONSTRAINT fk__ec_inventorymovement__product        FOREIGN KEY (inventorymovementproductid) REFERENCES public.ec_product (productid) ON DELETE RESTRICT,
    CONSTRAINT fk__ec_inventorymovement__order          FOREIGN KEY (inventorymovementorderid)   REFERENCES public.ec_order (orderid)     ON DELETE RESTRICT,
    CONSTRAINT fk__ec_inventorymovement__admin          FOREIGN KEY (inventorymovementadminid)   REFERENCES public.ec_admin (adminid)     ON DELETE RESTRICT,
    CONSTRAINT ck__ec_inventorymovement__type           CHECK (inventorymovementtype IN ('RESTOCK', 'ADJUSTMENT', 'SALE', 'ORDER_CANCELLED', 'REFUND_RETURN')),
    CONSTRAINT ck__ec_inventorymovement__quantitychange CHECK (inventorymovementquantitychange <> 0),
    CONSTRAINT ck__ec_inventorymovement__stockafter     CHECK (inventorymovementstockafter >= 0)
);

CREATE INDEX IF NOT EXISTS ix__ec_inventorymovement__productid_createdat ON public.ec_inventory_movement (inventorymovementproductid, inventorymovementcreatedat DESC);
CREATE INDEX IF NOT EXISTS ix__ec_inventorymovement__orderid             ON public.ec_inventory_movement (inventorymovementorderid);
CREATE INDEX IF NOT EXISTS ix__ec_inventorymovement__adminid             ON public.ec_inventory_movement (inventorymovementadminid);


-- ---------------------------------------------------------------------
-- ec_review : product ratings & reviews (RC-24)
--   REMOVED = moderated out by an admin; DELETED = deleted by the customer.
--   One live (non-DELETED) review per customer per product.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_review (
    reviewid                    BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    reviewproductid             BIGINT      NOT NULL,
    reviewcustomerid            BIGINT      NOT NULL,
    reviewrating                SMALLINT    NOT NULL,
    reviewtitle                 CITEXT,
    reviewcomment               TEXT,
    reviewstatus                CITEXT      NOT NULL DEFAULT 'PUBLISHED',
    reviewmoderatedbyadminid    INTEGER,
    reviewmoderatedat           TIMESTAMP WITHOUT TIME ZONE,
    reviewmoderationreason      TEXT,
    reviewcreatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    reviewupdatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_review__id        PRIMARY KEY (reviewid),
    CONSTRAINT fk__ec_review__product   FOREIGN KEY (reviewproductid)          REFERENCES public.ec_product (productid)   ON DELETE RESTRICT,
    CONSTRAINT fk__ec_review__customer  FOREIGN KEY (reviewcustomerid)         REFERENCES public.ec_customer (customerid) ON DELETE RESTRICT,
    CONSTRAINT fk__ec_review__admin     FOREIGN KEY (reviewmoderatedbyadminid) REFERENCES public.ec_admin (adminid)       ON DELETE RESTRICT,
    CONSTRAINT ck__ec_review__rating    CHECK (reviewrating BETWEEN 1 AND 5),
    CONSTRAINT ck__ec_review__status    CHECK (reviewstatus IN ('PENDING', 'PUBLISHED', 'REMOVED', 'DELETED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_review__productid_status_createdat ON public.ec_review (reviewproductid, reviewstatus, reviewcreatedat DESC);
CREATE INDEX IF NOT EXISTS ix__ec_review__customerid                 ON public.ec_review (reviewcustomerid);
CREATE INDEX IF NOT EXISTS ix__ec_review__moderatedbyadminid         ON public.ec_review (reviewmoderatedbyadminid);

CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_review__product_customer
    ON public.ec_review (reviewproductid, reviewcustomerid)
    WHERE reviewstatus <> 'DELETED';


-- ---------------------------------------------------------------------
-- ec_notification : outbox + delivery log (RC-25)
--   Exactly one recipient: a customer OR an admin.
--   SECURITY: never persist raw password-reset tokens in notificationbody.
--   New channels (SMS, PUSH, IN_APP) = extend ck__ec_notification__channel.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_notification (
    notificationid              BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    notificationcustomerid      BIGINT,
    notificationadminid         INTEGER,
    notificationorderid         BIGINT,
    notificationchannel         CITEXT      NOT NULL DEFAULT 'EMAIL',
    notificationtype            CITEXT      NOT NULL,
    notificationrecipient       CITEXT      NOT NULL,
    notificationsubject         CITEXT,
    notificationbody            TEXT,
    notificationstatus          CITEXT      NOT NULL DEFAULT 'PENDING',
    notificationattemptcount    INTEGER     NOT NULL DEFAULT 0,
    notificationsentat          TIMESTAMP WITHOUT TIME ZONE,
    notificationfailurereason   TEXT,
    notificationcreatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    notificationupdatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_notification__id              PRIMARY KEY (notificationid),
    CONSTRAINT fk__ec_notification__customer        FOREIGN KEY (notificationcustomerid) REFERENCES public.ec_customer (customerid) ON DELETE RESTRICT,
    CONSTRAINT fk__ec_notification__admin           FOREIGN KEY (notificationadminid)    REFERENCES public.ec_admin (adminid)       ON DELETE RESTRICT,
    CONSTRAINT fk__ec_notification__order           FOREIGN KEY (notificationorderid)    REFERENCES public.ec_order (orderid)       ON DELETE SET NULL,
    CONSTRAINT ck__ec_notification__recipient       CHECK (num_nonnulls(notificationcustomerid, notificationadminid) = 1),
    CONSTRAINT ck__ec_notification__channel         CHECK (notificationchannel IN ('EMAIL')),
    CONSTRAINT ck__ec_notification__type            CHECK (notificationtype IN ('REGISTRATION', 'ORDER_CONFIRMATION', 'PAYMENT_CONFIRMATION', 'ORDER_SHIPPED', 'ORDER_DELIVERED', 'PASSWORD_RESET', 'PASSWORD_CHANGED')),
    CONSTRAINT ck__ec_notification__status          CHECK (notificationstatus IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck__ec_notification__attemptcount    CHECK (notificationattemptcount >= 0)
);

CREATE INDEX IF NOT EXISTS ix__ec_notification__status_createdat ON public.ec_notification (notificationstatus, notificationcreatedat);
CREATE INDEX IF NOT EXISTS ix__ec_notification__customerid       ON public.ec_notification (notificationcustomerid);
CREATE INDEX IF NOT EXISTS ix__ec_notification__adminid          ON public.ec_notification (notificationadminid);
CREATE INDEX IF NOT EXISTS ix__ec_notification__orderid          ON public.ec_notification (notificationorderid);
