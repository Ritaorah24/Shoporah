-- =====================================================================
-- V6: Checkout, orders & payments
--   ec_delivery_method, ec_coupon, ec_order, ec_order_item,
--   ec_order_status_history, ec_payment
-- =====================================================================
-- Orders are immutable snapshots: delivery address, delivery fee and
-- item name/SKU/unit price are copied at checkout so later edits to
-- addresses or products never change order history.
-- =====================================================================


-- ---------------------------------------------------------------------
-- ec_delivery_method : flat fee per method (RC-20)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_delivery_method (
    deliverymethodid                INTEGER         NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    deliverymethodcode              CITEXT          NOT NULL,
    deliverymethodname              CITEXT          NOT NULL,
    deliverymethoddescription       TEXT,
    deliverymethodfee               NUMERIC(12, 2)  NOT NULL DEFAULT 0,
    deliverymethodestimatedmindays  SMALLINT,
    deliverymethodestimatedmaxdays  SMALLINT,
    deliverymethodstatus            CITEXT          NOT NULL DEFAULT 'ACTIVE',
    deliverymethodcreatedat         TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    deliverymethodupdatedat         TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_deliverymethod__id            PRIMARY KEY (deliverymethodid),
    CONSTRAINT uq__ec_deliverymethod__code          UNIQUE (deliverymethodcode),
    CONSTRAINT ck__ec_deliverymethod__fee           CHECK (deliverymethodfee >= 0),
    CONSTRAINT ck__ec_deliverymethod__estimateddays CHECK (
        (deliverymethodestimatedmindays IS NULL OR deliverymethodestimatedmindays >= 0) AND
        (deliverymethodestimatedmaxdays IS NULL OR deliverymethodestimatedmaxdays >= 0) AND
        (deliverymethodestimatedmindays IS NULL OR deliverymethodestimatedmaxdays IS NULL
            OR deliverymethodestimatedmaxdays >= deliverymethodestimatedmindays)
    ),
    CONSTRAINT ck__ec_deliverymethod__status        CHECK (deliverymethodstatus IN ('ACTIVE', 'INACTIVE'))
);


-- ---------------------------------------------------------------------
-- ec_coupon (RC-22)
--   "Expired"   = couponexpiresat has passed          (derived, not stored)
--   "Exhausted" = couponusagecount >= couponusagelimit (derived, not stored)
--   couponusagelimit NULL = unlimited
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_coupon (
    couponid                    INTEGER         NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    couponcode                  CITEXT          NOT NULL,
    coupondescription           TEXT,
    coupondiscounttype          CITEXT          NOT NULL,
    coupondiscountvalue         NUMERIC(12, 2)  NOT NULL,
    couponmaxdiscountamount     NUMERIC(12, 2),
    couponminimumordervalue     NUMERIC(12, 2)  NOT NULL DEFAULT 0,
    couponusagelimit            INTEGER,
    couponusagecount            INTEGER         NOT NULL DEFAULT 0,
    couponstartsat              TIMESTAMP WITHOUT TIME ZONE,
    couponexpiresat             TIMESTAMP WITHOUT TIME ZONE,
    couponcreatedbyadminid      INTEGER         NOT NULL,
    couponstatus                CITEXT          NOT NULL DEFAULT 'ACTIVE',
    couponcreatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    couponupdatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_coupon__id                    PRIMARY KEY (couponid),
    CONSTRAINT uq__ec_coupon__code                  UNIQUE (couponcode),
    CONSTRAINT fk__ec_coupon__admin                 FOREIGN KEY (couponcreatedbyadminid) REFERENCES public.ec_admin (adminid) ON DELETE RESTRICT,
    CONSTRAINT ck__ec_coupon__discounttype          CHECK (coupondiscounttype IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT ck__ec_coupon__discountvalue         CHECK (coupondiscountvalue > 0 AND (coupondiscounttype <> 'PERCENTAGE' OR coupondiscountvalue <= 100)),
    CONSTRAINT ck__ec_coupon__maxdiscountamount     CHECK (couponmaxdiscountamount IS NULL OR couponmaxdiscountamount > 0),
    CONSTRAINT ck__ec_coupon__minimumordervalue     CHECK (couponminimumordervalue >= 0),
    CONSTRAINT ck__ec_coupon__usagelimit            CHECK (couponusagelimit IS NULL OR couponusagelimit > 0),
    CONSTRAINT ck__ec_coupon__usagecount            CHECK (couponusagecount >= 0 AND (couponusagelimit IS NULL OR couponusagecount <= couponusagelimit)),
    CONSTRAINT ck__ec_coupon__validityperiod        CHECK (couponstartsat IS NULL OR couponexpiresat IS NULL OR couponexpiresat > couponstartsat),
    CONSTRAINT ck__ec_coupon__status                CHECK (couponstatus IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_coupon__status_expiresat  ON public.ec_coupon (couponstatus, couponexpiresat);
CREATE INDEX IF NOT EXISTS ix__ec_coupon__createdbyadminid  ON public.ec_coupon (couponcreatedbyadminid);


-- ---------------------------------------------------------------------
-- ec_order
--   orderstatus        : fulfilment lifecycle (PRD section 6)
--   orderpaymentstatus : order-level payment summary (attempts live in ec_payment)
--   ordertotal         : enforced = subtotal + delivery fee - discount
--   orderidempotencykey: client-generated UUID per checkout attempt; a retried
--                        request hits uq__ec_order__customerid_idempotencykey
--                        instead of creating a duplicate order
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_order (
    orderid                     BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    orderreference              CITEXT          NOT NULL,
    orderidempotencykey         UUID            NOT NULL,
    ordercustomerid             BIGINT          NOT NULL,
    ordercustomeraddressid      BIGINT,
    orderdeliverymethodid       INTEGER         NOT NULL,
    ordercouponid               INTEGER,
    -- delivery address snapshot
    orderrecipientname          CITEXT          NOT NULL,
    orderrecipientphonenumber   CITEXT          NOT NULL,
    orderaddressline1           CITEXT          NOT NULL,
    orderaddressline2           CITEXT,
    ordercity                   CITEXT          NOT NULL,
    orderstate                  CITEXT          NOT NULL,
    ordercountry                CITEXT          NOT NULL,
    orderpostalcode             CITEXT,
    -- totals (server-calculated)
    ordersubtotal               NUMERIC(12, 2)  NOT NULL,
    orderdeliveryfee            NUMERIC(12, 2)  NOT NULL DEFAULT 0,
    orderdiscountamount         NUMERIC(12, 2)  NOT NULL DEFAULT 0,
    ordertotal                  NUMERIC(12, 2)  NOT NULL,
    orderstatus                 CITEXT          NOT NULL DEFAULT 'PENDING',
    orderpaymentstatus          CITEXT          NOT NULL DEFAULT 'UNPAID',
    orderpaidat                 TIMESTAMP WITHOUT TIME ZONE,
    ordercreatedat              TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    orderupdatedat              TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_order__id                 PRIMARY KEY (orderid),
    CONSTRAINT uq__ec_order__reference          UNIQUE (orderreference),
    CONSTRAINT uq__ec_order__customerid_idempotencykey UNIQUE (ordercustomerid, orderidempotencykey),
    CONSTRAINT fk__ec_order__customer           FOREIGN KEY (ordercustomerid)        REFERENCES public.ec_customer (customerid)                ON DELETE RESTRICT,
    CONSTRAINT fk__ec_order__customeraddress    FOREIGN KEY (ordercustomeraddressid) REFERENCES public.ec_customer_address (customeraddressid) ON DELETE SET NULL,
    CONSTRAINT fk__ec_order__deliverymethod     FOREIGN KEY (orderdeliverymethodid)  REFERENCES public.ec_delivery_method (deliverymethodid)   ON DELETE RESTRICT,
    CONSTRAINT fk__ec_order__coupon             FOREIGN KEY (ordercouponid)          REFERENCES public.ec_coupon (couponid)                    ON DELETE RESTRICT,
    CONSTRAINT ck__ec_order__subtotal           CHECK (ordersubtotal >= 0),
    CONSTRAINT ck__ec_order__deliveryfee        CHECK (orderdeliveryfee >= 0),
    CONSTRAINT ck__ec_order__discountamount     CHECK (orderdiscountamount >= 0 AND orderdiscountamount <= ordersubtotal),
    CONSTRAINT ck__ec_order__total              CHECK (ordertotal >= 0 AND ordertotal = ordersubtotal + orderdeliveryfee - orderdiscountamount),
    CONSTRAINT ck__ec_order__status             CHECK (orderstatus IN ('PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT ck__ec_order__paymentstatus      CHECK (orderpaymentstatus IN ('UNPAID', 'PAID', 'REFUNDED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_order__customerid_createdat   ON public.ec_order (ordercustomerid, ordercreatedat DESC);
CREATE INDEX IF NOT EXISTS ix__ec_order__status_createdat       ON public.ec_order (orderstatus, ordercreatedat);
CREATE INDEX IF NOT EXISTS ix__ec_order__paymentstatus          ON public.ec_order (orderpaymentstatus);
CREATE INDEX IF NOT EXISTS ix__ec_order__createdat              ON public.ec_order (ordercreatedat);
CREATE INDEX IF NOT EXISTS ix__ec_order__customeraddressid      ON public.ec_order (ordercustomeraddressid);
CREATE INDEX IF NOT EXISTS ix__ec_order__deliverymethodid       ON public.ec_order (orderdeliverymethodid);
CREATE INDEX IF NOT EXISTS ix__ec_order__couponid               ON public.ec_order (ordercouponid);


-- ---------------------------------------------------------------------
-- ec_order_item : product snapshot per order line (rows never change)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_order_item (
    orderitemid             BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    orderitemorderid        BIGINT          NOT NULL,
    orderitemproductid      BIGINT          NOT NULL,
    orderitemproductname    CITEXT          NOT NULL,
    orderitemproductsku     CITEXT          NOT NULL,
    orderitemunitprice      NUMERIC(12, 2)  NOT NULL,
    orderitemquantity       INTEGER         NOT NULL,
    orderitemlinetotal      NUMERIC(12, 2)  GENERATED ALWAYS AS (orderitemunitprice * orderitemquantity) STORED,
    orderitemcreatedat      TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_orderitem__id                 PRIMARY KEY (orderitemid),
    CONSTRAINT uq__ec_orderitem__orderid_productid  UNIQUE (orderitemorderid, orderitemproductid),
    CONSTRAINT fk__ec_orderitem__order              FOREIGN KEY (orderitemorderid)   REFERENCES public.ec_order (orderid)     ON DELETE CASCADE,
    CONSTRAINT fk__ec_orderitem__product            FOREIGN KEY (orderitemproductid) REFERENCES public.ec_product (productid) ON DELETE RESTRICT,
    CONSTRAINT ck__ec_orderitem__unitprice          CHECK (orderitemunitprice >= 0),
    CONSTRAINT ck__ec_orderitem__quantity           CHECK (orderitemquantity > 0)
);

CREATE INDEX IF NOT EXISTS ix__ec_orderitem__productid ON public.ec_order_item (orderitemproductid);


-- ---------------------------------------------------------------------
-- ec_order_status_history : audit of every order status transition
--   actor = admin, customer (cancellation), or neither (system)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_order_status_history (
    orderstatushistoryid                    BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    orderstatushistoryorderid               BIGINT      NOT NULL,
    orderstatushistoryfromstatus            CITEXT,
    orderstatushistorytostatus              CITEXT      NOT NULL,
    orderstatushistorychangedbyadminid      INTEGER,
    orderstatushistorychangedbycustomerid   BIGINT,
    orderstatushistorynote                  TEXT,
    orderstatushistorycreatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_orderstatushistory__id            PRIMARY KEY (orderstatushistoryid),
    CONSTRAINT fk__ec_orderstatushistory__order         FOREIGN KEY (orderstatushistoryorderid)             REFERENCES public.ec_order (orderid)       ON DELETE CASCADE,
    CONSTRAINT fk__ec_orderstatushistory__admin         FOREIGN KEY (orderstatushistorychangedbyadminid)    REFERENCES public.ec_admin (adminid)       ON DELETE RESTRICT,
    CONSTRAINT fk__ec_orderstatushistory__customer      FOREIGN KEY (orderstatushistorychangedbycustomerid) REFERENCES public.ec_customer (customerid) ON DELETE RESTRICT,
    CONSTRAINT ck__ec_orderstatushistory__fromstatus    CHECK (orderstatushistoryfromstatus IS NULL OR orderstatushistoryfromstatus IN ('PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT ck__ec_orderstatushistory__tostatus      CHECK (orderstatushistorytostatus IN ('PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED', 'REFUNDED')),
    CONSTRAINT ck__ec_orderstatushistory__actor         CHECK (num_nonnulls(orderstatushistorychangedbyadminid, orderstatushistorychangedbycustomerid) <= 1)
);

CREATE INDEX IF NOT EXISTS ix__ec_orderstatushistory__orderid_createdat ON public.ec_order_status_history (orderstatushistoryorderid, orderstatushistorycreatedat);
CREATE INDEX IF NOT EXISTS ix__ec_orderstatushistory__adminid           ON public.ec_order_status_history (orderstatushistorychangedbyadminid);
CREATE INDEX IF NOT EXISTS ix__ec_orderstatushistory__customerid        ON public.ec_order_status_history (orderstatushistorychangedbycustomerid);


-- ---------------------------------------------------------------------
-- ec_payment : one row per payment attempt (RC-23)
--   At most one SUCCESS payment per order (partial unique index below).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_payment (
    paymentid                       BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    paymentorderid                  BIGINT          NOT NULL,
    paymentreference                CITEXT          NOT NULL,
    paymentprovider                 CITEXT          NOT NULL,
    paymentprovidertransactionid    TEXT,
    paymentamount                   NUMERIC(12, 2)  NOT NULL,
    paymentcurrency                 CITEXT          NOT NULL DEFAULT 'NGN',
    paymentstatus                   CITEXT          NOT NULL DEFAULT 'PENDING',
    paymentauthorizationurl         TEXT,
    paymentchannel                  CITEXT,
    paymentgatewayresponse          TEXT,
    paymentproviderresponse         JSONB,
    paymentpaidat                   TIMESTAMP WITHOUT TIME ZONE,
    paymentverifiedat               TIMESTAMP WITHOUT TIME ZONE,
    paymentcreatedat                TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    paymentupdatedat                TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_payment__id           PRIMARY KEY (paymentid),
    CONSTRAINT uq__ec_payment__reference    UNIQUE (paymentreference),
    CONSTRAINT fk__ec_payment__order        FOREIGN KEY (paymentorderid) REFERENCES public.ec_order (orderid) ON DELETE RESTRICT,
    CONSTRAINT ck__ec_payment__provider     CHECK (paymentprovider IN ('PAYSTACK', 'FLUTTERWAVE')),
    CONSTRAINT ck__ec_payment__amount       CHECK (paymentamount > 0),
    CONSTRAINT ck__ec_payment__status       CHECK (paymentstatus IN ('PENDING', 'SUCCESS', 'FAILED', 'ABANDONED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_payment__orderid          ON public.ec_payment (paymentorderid);
CREATE INDEX IF NOT EXISTS ix__ec_payment__status_createdat ON public.ec_payment (paymentstatus, paymentcreatedat);

CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_payment__provider_transactionid
    ON public.ec_payment (paymentprovider, paymentprovidertransactionid)
    WHERE paymentprovidertransactionid IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_payment__order_success
    ON public.ec_payment (paymentorderid)
    WHERE paymentstatus = 'SUCCESS';
