-- =====================================================================
-- V3: Identity & access
--   ec_role, ec_admin, ec_admin_auth,
--   ec_customer, ec_customer_auth, ec_customer_address
-- =====================================================================
-- Profile and credentials are separated (same pattern as the reference
-- cl_admin / cl_admin_auth). Auth tables hold hashes only, never raw
-- passwords or tokens.
-- =====================================================================


-- ---------------------------------------------------------------------
-- ec_role : admin roles (customers have no role row; RC-6)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_role (
    roleid                  INTEGER     NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    rolename                CITEXT      NOT NULL,
    roledescription         TEXT,
    rolestatus              CITEXT      NOT NULL DEFAULT 'ACTIVE',
    rolecreatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    roleupdatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_role__id      PRIMARY KEY (roleid),
    CONSTRAINT uq__ec_role__name    UNIQUE (rolename),
    CONSTRAINT ck__ec_role__status  CHECK (rolestatus IN ('ACTIVE', 'INACTIVE'))
);


-- ---------------------------------------------------------------------
-- ec_admin : admin profile (one role per admin)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_admin (
    adminid                 INTEGER     NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    adminroleid             INTEGER     NOT NULL,
    adminfirstname          CITEXT      NOT NULL,
    adminlastname           CITEXT      NOT NULL,
    adminemail              CITEXT      NOT NULL,
    adminphonenumber        CITEXT,
    adminstatus             CITEXT      NOT NULL DEFAULT 'ACTIVE',
    admincreatedat          TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    adminupdatedat          TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_admin__id     PRIMARY KEY (adminid),
    CONSTRAINT uq__ec_admin__email  UNIQUE (adminemail),
    CONSTRAINT fk__ec_admin__role   FOREIGN KEY (adminroleid) REFERENCES public.ec_role (roleid) ON DELETE RESTRICT,
    CONSTRAINT ck__ec_admin__status CHECK (adminstatus IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DELETED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_admin__roleid ON public.ec_admin (adminroleid);

-- ---------------------------------------------------------------------
-- ec_admin_auth : admin credentials & security state (1:1 with ec_admin)
-- No refresh tokens: login issues a short-lived JWT access token only.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_admin_auth (
    adminauthid                     INTEGER     NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    adminauthadminid                INTEGER     NOT NULL,
    adminauthpasswordhash           TEXT,
    adminauthpasswordstatus         CITEXT      NOT NULL DEFAULT 'ACTIVE',
    adminauthpasswordchangedat      TIMESTAMP WITHOUT TIME ZONE,
    adminauthfailedloginattempts    INTEGER     NOT NULL DEFAULT 0,
    adminauthlastfailedloginat      TIMESTAMP WITHOUT TIME ZONE,
    adminauthlockeduntil            TIMESTAMP WITHOUT TIME ZONE,
    adminauthlastloginat            TIMESTAMP WITHOUT TIME ZONE,
    adminauthresettokenhash         TEXT,
    adminauthresettokenexpiresat    TIMESTAMP WITHOUT TIME ZONE,
    adminauthstatus                 CITEXT      NOT NULL DEFAULT 'ACTIVE',
    adminauthcreatedat              TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    adminauthupdatedat              TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_adminauth__id                     PRIMARY KEY (adminauthid),
    CONSTRAINT uq__ec_adminauth__adminid                UNIQUE (adminauthadminid),
    CONSTRAINT fk__ec_adminauth__admin                  FOREIGN KEY (adminauthadminid) REFERENCES public.ec_admin (adminid) ON DELETE CASCADE,
    CONSTRAINT ck__ec_adminauth__passwordstatus         CHECK (adminauthpasswordstatus IN ('ACTIVE', 'MUST_CHANGE')),
    CONSTRAINT ck__ec_adminauth__failedloginattempts    CHECK (adminauthfailedloginattempts >= 0),
    CONSTRAINT ck__ec_adminauth__status                 CHECK (adminauthstatus IN ('ACTIVE', 'LOCKED', 'DISABLED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_adminauth__resettokenhash
    ON public.ec_admin_auth (adminauthresettokenhash)
    WHERE adminauthresettokenhash IS NOT NULL;


-- ---------------------------------------------------------------------
-- ec_customer : customer profile (no credentials)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_customer (
    customerid              BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    customerfirstname       CITEXT      NOT NULL,
    customerlastname        CITEXT      NOT NULL,
    customeremail           CITEXT      NOT NULL,
    customerphonenumber     CITEXT,
    customerstatus          CITEXT      NOT NULL DEFAULT 'ACTIVE',
    customercreatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    customerupdatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_customer__id      PRIMARY KEY (customerid),
    CONSTRAINT uq__ec_customer__email   UNIQUE (customeremail),
    CONSTRAINT ck__ec_customer__status  CHECK (customerstatus IN ('ACTIVE', 'SUSPENDED', 'DEACTIVATED','DELETED'))
);

-- Phone is indexed but NOT unique (RC-5)
CREATE INDEX IF NOT EXISTS ix__ec_customer__phonenumber ON public.ec_customer (customerphonenumber);
CREATE INDEX IF NOT EXISTS ix__ec_customer__status      ON public.ec_customer (customerstatus);
CREATE INDEX IF NOT EXISTS ix__ec_customer__createdat   ON public.ec_customer (customercreatedat);


-- ---------------------------------------------------------------------
-- ec_customer_auth : customer credentials & security state (1:1)
-- No refresh tokens: login issues a short-lived JWT access token only.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_customer_auth (
    customerauthid                  BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    customerauthcustomerid          BIGINT      NOT NULL,
    customerauthpasswordhash        TEXT        NOT NULL,
    customerauthpasswordchangedat   TIMESTAMP WITHOUT TIME ZONE,
    customerauthfailedloginattempts INTEGER     NOT NULL DEFAULT 0,
    customerauthlastfailedloginat   TIMESTAMP WITHOUT TIME ZONE,
    customerauthlockeduntil         TIMESTAMP WITHOUT TIME ZONE,
    customerauthlastloginat         TIMESTAMP WITHOUT TIME ZONE,
    customerauthresettokenhash      TEXT,
    customerauthresettokenexpiresat TIMESTAMP WITHOUT TIME ZONE,
    customerauthstatus              CITEXT      NOT NULL DEFAULT 'ACTIVE',
    customerauthcreatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    customerauthupdatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_customerauth__id                  PRIMARY KEY (customerauthid),
    CONSTRAINT uq__ec_customerauth__customerid          UNIQUE (customerauthcustomerid),
    CONSTRAINT fk__ec_customerauth__customer            FOREIGN KEY (customerauthcustomerid) REFERENCES public.ec_customer (customerid) ON DELETE CASCADE,
    CONSTRAINT ck__ec_customerauth__failedloginattempts CHECK (customerauthfailedloginattempts >= 0),
    CONSTRAINT ck__ec_customerauth__status              CHECK (customerauthstatus IN ('ACTIVE', 'LOCKED', 'DISABLED','DELETED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_customerauth__resettokenhash
    ON public.ec_customer_auth (customerauthresettokenhash)
    WHERE customerauthresettokenhash IS NOT NULL;


-- ---------------------------------------------------------------------
-- ec_customer_address : delivery addresses (hard-deleted; orders keep a snapshot)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_customer_address (
    customeraddressid                   BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    customeraddresscustomerid           BIGINT      NOT NULL,
    customeraddressrecipientname        CITEXT      NOT NULL,
    customeraddressrecipientphonenumber CITEXT      NOT NULL,
    customeraddressline1                CITEXT      NOT NULL,
    customeraddressline2                CITEXT,
    customeraddresscity                 CITEXT      NOT NULL,
    customeraddressstate                CITEXT      NOT NULL,
    customeraddresscountry              CITEXT      NOT NULL,
    customeraddresspostalcode           CITEXT,
    customeraddressisdefault            BOOLEAN     NOT NULL DEFAULT FALSE,
    customeraddresscreatedat            TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    customeraddressupdatedat            TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_customeraddress__id       PRIMARY KEY (customeraddressid),
    CONSTRAINT fk__ec_customeraddress__customer FOREIGN KEY (customeraddresscustomerid) REFERENCES public.ec_customer (customerid) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix__ec_customeraddress__customerid ON public.ec_customer_address (customeraddresscustomerid);

-- At most one default address per customer
CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_customeraddress__default
    ON public.ec_customer_address (customeraddresscustomerid)
    WHERE customeraddressisdefault;
