-- =====================================================================
-- V5: Cart & wishlist
--   ec_cart, ec_cart_item, ec_wishlist, ec_wishlist_item
-- =====================================================================
-- One cart and one wishlist per customer, reused for the customer's
-- lifetime (no status column). Cart items deliberately store NO price:
-- subtotals are always computed server-side from ec_product.
-- =====================================================================


-- ---------------------------------------------------------------------
-- ec_cart (1:1 with ec_customer)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_cart (
    cartid                  BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    cartcustomerid          BIGINT      NOT NULL,
    cartcreatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    cartupdatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_cart__id          PRIMARY KEY (cartid),
    CONSTRAINT uq__ec_cart__customerid  UNIQUE (cartcustomerid),
    CONSTRAINT fk__ec_cart__customer    FOREIGN KEY (cartcustomerid) REFERENCES public.ec_customer (customerid) ON DELETE CASCADE
);


-- ---------------------------------------------------------------------
-- ec_cart_item (one row per product per cart)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_cart_item (
    cartitemid              BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    cartitemcartid          BIGINT      NOT NULL,
    cartitemproductid       BIGINT      NOT NULL,
    cartitemquantity        INTEGER     NOT NULL,
    cartitemcreatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    cartitemupdatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_cartitem__id                  PRIMARY KEY (cartitemid),
    CONSTRAINT uq__ec_cartitem__cartid_productid    UNIQUE (cartitemcartid, cartitemproductid),
    CONSTRAINT fk__ec_cartitem__cart                FOREIGN KEY (cartitemcartid)    REFERENCES public.ec_cart (cartid)       ON DELETE CASCADE,
    CONSTRAINT fk__ec_cartitem__product             FOREIGN KEY (cartitemproductid) REFERENCES public.ec_product (productid) ON DELETE CASCADE,
    CONSTRAINT ck__ec_cartitem__quantity            CHECK (cartitemquantity > 0)
);

CREATE INDEX IF NOT EXISTS ix__ec_cartitem__productid ON public.ec_cart_item (cartitemproductid);


-- ---------------------------------------------------------------------
-- ec_wishlist (1:1 with ec_customer)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_wishlist (
    wishlistid              BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    wishlistcustomerid      BIGINT      NOT NULL,
    wishlistcreatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    wishlistupdatedat       TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_wishlist__id          PRIMARY KEY (wishlistid),
    CONSTRAINT uq__ec_wishlist__customerid  UNIQUE (wishlistcustomerid),
    CONSTRAINT fk__ec_wishlist__customer    FOREIGN KEY (wishlistcustomerid) REFERENCES public.ec_customer (customerid) ON DELETE CASCADE
);


-- ---------------------------------------------------------------------
-- ec_wishlist_item (one row per product per wishlist; rows never change)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_wishlist_item (
    wishlistitemid          BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    wishlistitemwishlistid  BIGINT      NOT NULL,
    wishlistitemproductid   BIGINT      NOT NULL,
    wishlistitemcreatedat   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_wishlistitem__id                      PRIMARY KEY (wishlistitemid),
    CONSTRAINT uq__ec_wishlistitem__wishlistid_productid    UNIQUE (wishlistitemwishlistid, wishlistitemproductid),
    CONSTRAINT fk__ec_wishlistitem__wishlist                FOREIGN KEY (wishlistitemwishlistid) REFERENCES public.ec_wishlist (wishlistid) ON DELETE CASCADE,
    CONSTRAINT fk__ec_wishlistitem__product                 FOREIGN KEY (wishlistitemproductid)  REFERENCES public.ec_product (productid)   ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix__ec_wishlistitem__productid ON public.ec_wishlist_item (wishlistitemproductid);
