-- ---------------------------------------------------------------------
-- ec_category : flat product categories (RC-10)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_category (
    categoryid                  INTEGER     NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    categoryname                CITEXT      NOT NULL,
    categorydescription         TEXT,
    categorycreatedbyadminid    INTEGER     NOT NULL,
    categorystatus              CITEXT      NOT NULL DEFAULT 'ACTIVE',
    categorycreatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    categoryupdatedat           TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_category__id      PRIMARY KEY (categoryid),
    CONSTRAINT uq__ec_category__name    UNIQUE (categoryname),
    CONSTRAINT fk__ec_category__admin   FOREIGN KEY (categorycreatedbyadminid) REFERENCES public.ec_admin (adminid) ON DELETE RESTRICT,
    CONSTRAINT ck__ec_category__status  CHECK (categorystatus IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_category__status           ON public.ec_category (categorystatus);
CREATE INDEX IF NOT EXISTS ix__ec_category__createdbyadminid ON public.ec_category (categorycreatedbyadminid);


-- ---------------------------------------------------------------------
-- ec_brand : product brands, used for "filter by brand" (RC-11)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_brand (
    brandid                 INTEGER     NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    brandname               CITEXT      NOT NULL,
    brandstatus             CITEXT      NOT NULL DEFAULT 'ACTIVE',
    brandcreatedat          TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    brandupdatedat          TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_brand__id     PRIMARY KEY (brandid),
    CONSTRAINT uq__ec_brand__name   UNIQUE (brandname),
    CONSTRAINT ck__ec_brand__status CHECK (brandstatus IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);


-- ---------------------------------------------------------------------
-- ec_product : products; stock lives here (single source of truth)
--   productsellingprice  : generated = COALESCE(discountprice, price)
--   productsearchvector  : generated full-text vector (name A, keywords B, description C)
--   productaveragerating / productreviewcount / productsoldcount :
--       summary columns maintained in the same transaction as reviews / paid orders
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_product (
    productid                   BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    productcategoryid           INTEGER         NOT NULL,
    productbrandid              INTEGER,
    productcreatedbyadminid     INTEGER         NOT NULL,
    productname                 CITEXT          NOT NULL,
    productdescription          TEXT,
    productkeywords             TEXT,
    productsku                  CITEXT          NOT NULL,
    productprice                NUMERIC(12, 2)  NOT NULL,
    productdiscountprice        NUMERIC(12, 2),
    productsellingprice         NUMERIC(12, 2)  GENERATED ALWAYS AS (COALESCE(productdiscountprice, productprice)) STORED,
    productstockquantity        INTEGER         NOT NULL DEFAULT 0,
    productlowstockthreshold    INTEGER,
    productaveragerating        NUMERIC(3, 2)   NOT NULL DEFAULT 0,
    productreviewcount          INTEGER         NOT NULL DEFAULT 0,
    productsoldcount            INTEGER         NOT NULL DEFAULT 0,
    productsearchvector         TSVECTOR        GENERATED ALWAYS AS (
                                    setweight(to_tsvector('english', COALESCE(productname::TEXT, '')), 'A') ||
                                    setweight(to_tsvector('english', COALESCE(productkeywords, '')), 'B') ||
                                    setweight(to_tsvector('english', COALESCE(productdescription, '')), 'C')
                                ) STORED,
    productstatus               CITEXT          NOT NULL DEFAULT 'ACTIVE',
    productcreatedat            TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    productupdatedat            TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_product__id                   PRIMARY KEY (productid),
    CONSTRAINT uq__ec_product__sku                  UNIQUE (productsku),
    CONSTRAINT fk__ec_product__category             FOREIGN KEY (productcategoryid)       REFERENCES public.ec_category (categoryid) ON DELETE RESTRICT,
    CONSTRAINT fk__ec_product__brand                FOREIGN KEY (productbrandid)          REFERENCES public.ec_brand (brandid)       ON DELETE RESTRICT,
    CONSTRAINT fk__ec_product__admin                FOREIGN KEY (productcreatedbyadminid) REFERENCES public.ec_admin (adminid)       ON DELETE RESTRICT,
    CONSTRAINT ck__ec_product__price                CHECK (productprice > 0),
    CONSTRAINT ck__ec_product__discountprice        CHECK (productdiscountprice IS NULL OR (productdiscountprice >= 0 AND productdiscountprice < productprice)),
    CONSTRAINT ck__ec_product__stockquantity        CHECK (productstockquantity >= 0),
    CONSTRAINT ck__ec_product__lowstockthreshold    CHECK (productlowstockthreshold IS NULL OR productlowstockthreshold >= 0),
    CONSTRAINT ck__ec_product__averagerating        CHECK (productaveragerating BETWEEN 0 AND 5),
    CONSTRAINT ck__ec_product__reviewcount          CHECK (productreviewcount >= 0),
    CONSTRAINT ck__ec_product__soldcount            CHECK (productsoldcount >= 0),
    CONSTRAINT ck__ec_product__status               CHECK (productstatus IN ('ACTIVE', 'INACTIVE', 'DELETED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_product__categoryid           ON public.ec_product (productcategoryid);
CREATE INDEX IF NOT EXISTS ix__ec_product__brandid              ON public.ec_product (productbrandid);
CREATE INDEX IF NOT EXISTS ix__ec_product__createdbyadminid     ON public.ec_product (productcreatedbyadminid);
CREATE INDEX IF NOT EXISTS ix__ec_product__status_sellingprice  ON public.ec_product (productstatus, productsellingprice);
CREATE INDEX IF NOT EXISTS ix__ec_product__status_createdat     ON public.ec_product (productstatus, productcreatedat DESC);
CREATE INDEX IF NOT EXISTS ix__ec_product__averagerating        ON public.ec_product (productaveragerating);
CREATE INDEX IF NOT EXISTS ix__ec_product__soldcount            ON public.ec_product (productsoldcount);
CREATE INDEX IF NOT EXISTS ix__ec_product__stockquantity        ON public.ec_product (productstockquantity);
CREATE INDEX IF NOT EXISTS ix__ec_product__searchvector         ON public.ec_product USING GIN (productsearchvector);
-- Partial-word name search: query with (productname::TEXT) ILIKE '%term%'
CREATE INDEX IF NOT EXISTS ix__ec_product__name_trgm            ON public.ec_product USING GIN ((productname::TEXT) gin_trgm_ops);


-- ---------------------------------------------------------------------
-- ec_product_image : product images stored in external file storage (RC-28)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ec_product_image (
    productimageid          BIGINT      NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    productimageproductid   BIGINT      NOT NULL,
    productimageurl         TEXT        NOT NULL,
    productimagestoragekey  TEXT        NOT NULL,
    productimagealttext     CITEXT,
    productimagesortorder   INTEGER     NOT NULL DEFAULT 0,
    productimageisprimary   BOOLEAN     NOT NULL DEFAULT FALSE,
    productimagecreatedat   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    productimageupdatedat   TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_productimage__id          PRIMARY KEY (productimageid),
    CONSTRAINT uq__ec_productimage__storagekey  UNIQUE (productimagestoragekey),
    CONSTRAINT fk__ec_productimage__product     FOREIGN KEY (productimageproductid) REFERENCES public.ec_product (productid) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix__ec_productimage__productid_sortorder
    ON public.ec_product_image (productimageproductid, productimagesortorder);

-- At most one primary image per product
CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_productimage__primary
    ON public.ec_product_image (productimageproductid)
    WHERE productimageisprimary;
