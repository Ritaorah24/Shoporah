-- =====================================================================
-- V13: Refunds through the payment provider (checkpoint 2.2)
-- =====================================================================
-- ec_refund : one row per refund attempt, like ec_payment for payments.
--   A refund is asynchronous at Paystack: it starts PENDING and becomes
--   PROCESSED (money sent back) or FAILED later. The payment row stays
--   SUCCESS: the payment did happen; the refund is tracked here.
--   refundproviderrefundid NULL = Paystack has not confirmed it yet.
--   refundproviderstatus   = Paystack's own word (pending, processing,
--                            needs-attention, processed, failed).
--   refundrestock          = put the sold stock back (delivered orders
--                            that are returned) once it is PROCESSED.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.ec_refund (
    refundid                    BIGINT          NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1),
    refundorderid               BIGINT          NOT NULL,
    refundpaymentid             BIGINT          NOT NULL,
    refundamount                NUMERIC(12, 2)  NOT NULL,
    refundcurrency              CITEXT          NOT NULL DEFAULT 'NGN',
    refundstatus                CITEXT          NOT NULL DEFAULT 'PENDING',
    refundproviderrefundid      TEXT,
    refundproviderstatus        CITEXT,
    refundreason                TEXT            NOT NULL,
    refundrestock               BOOLEAN         NOT NULL DEFAULT FALSE,
    refundrequestedbyadminid    INTEGER         NOT NULL,
    refundfailurereason         TEXT,
    refundproviderresponse      JSONB,
    refundprocessedat           TIMESTAMP WITHOUT TIME ZONE,
    refundcreatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    refundupdatedat             TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (timezone('UTC', CURRENT_TIMESTAMP(6)))::TIMESTAMP + (1::NUMERIC || ' HOUR')::INTERVAL,
    CONSTRAINT pk__ec_refund__id        PRIMARY KEY (refundid),
    CONSTRAINT fk__ec_refund__order     FOREIGN KEY (refundorderid)            REFERENCES public.ec_order (orderid)     ON DELETE RESTRICT,
    CONSTRAINT fk__ec_refund__payment   FOREIGN KEY (refundpaymentid)          REFERENCES public.ec_payment (paymentid) ON DELETE RESTRICT,
    CONSTRAINT fk__ec_refund__admin     FOREIGN KEY (refundrequestedbyadminid) REFERENCES public.ec_admin (adminid)     ON DELETE RESTRICT,
    CONSTRAINT ck__ec_refund__amount    CHECK (refundamount > 0),
    CONSTRAINT ck__ec_refund__status    CHECK (refundstatus IN ('PENDING', 'PROCESSED', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS ix__ec_refund__orderid   ON public.ec_refund (refundorderid);
CREATE INDEX IF NOT EXISTS ix__ec_refund__adminid   ON public.ec_refund (refundrequestedbyadminid);

-- Paystack's refund id belongs to one of our refunds only.
CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_refund__providerrefundid
    ON public.ec_refund (refundproviderrefundid)
    WHERE refundproviderrefundid IS NOT NULL;

-- At most one refund in progress or done per payment: a double click or two
-- admins can never refund twice. A FAILED refund does not count, so it can be retried.
CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_refund__payment_active
    ON public.ec_refund (refundpaymentid)
    WHERE refundstatus IN ('PENDING', 'PROCESSED');

-- Returned stock is put back at most once per refunded order and product (like V12).
CREATE UNIQUE INDEX IF NOT EXISTS uq__ec_inventorymovement__order_refund
    ON public.ec_inventory_movement (inventorymovementorderid, inventorymovementproductid)
    WHERE inventorymovementtype = 'REFUND_RETURN';
